# Write code that calculates how many tablespoons are needed to get X grams of sugar,
# X being a variable. The program must display the following text at the end:
# "For x grams of sugar, you need y tablespoons"
# Note: one tablespoon is about 15 grams of sugar

X = 55  # Amount of sugar in grams

Y = X / 15  # Number of tablespoons

print("For", X, "grams of sugar, you need", Y, "tablespoons")